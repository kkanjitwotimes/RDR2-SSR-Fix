#!/usr/bin/env python3
# Regenerates src/shaders/spv.inc from cas.vert / cas.frag. Needs glslangValidator (glslang-tools) on PATH.
# Only needed when a shader changes; the generated spv.inc is committed, so a normal build does not need glslang.
import struct, subprocess, sys, os
d = os.path.dirname(os.path.abspath(__file__))
def arr(name, src):
    spv = os.path.join(d, src + ".spv")
    subprocess.check_call(["glslangValidator", "-V", os.path.join(d, src), "-o", spv])
    b = open(spv, "rb").read(); w = struct.unpack("<%dI" % (len(b) // 4), b); os.remove(spv)
    rows = ["  " + ", ".join("0x%08x" % x for x in w[i:i + 8]) + "," for i in range(0, len(w), 8)]
    return "static const uint32_t %s[] = {\n%s\n};\n" % (name, "\n".join(rows))
open(os.path.join(d, "spv.inc"), "w").write("// Generated by gen_spv.py from cas.vert / cas.frag (glslangValidator -V).\n" + arr("kCasVertSpv", "cas.vert") + arr("kCasFragSpv", "cas.frag"))
print("wrote spv.inc")
